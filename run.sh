#!/bin/bash
set -e

# -------------------------------------------------------------------
# Base Directory
# -------------------------------------------------------------------

BASE_DIR="$(cd "$(dirname "$0")" && pwd)"

# -------------------------------------------------------------------
# Configuration
# -------------------------------------------------------------------

source "$BASE_DIR/config/global.conf"

# -------------------------------------------------------------------
# Command-line Interface
# -------------------------------------------------------------------

source "$BASE_DIR/cli/init.sh"
parse_args "$@"

# -------------------------------------------------------------------
# Core Framework
# -------------------------------------------------------------------

source "$BASE_DIR/core/init.sh"

# -------------------------------------------------------------------
# Profile
# -------------------------------------------------------------------

source "$BASE_DIR/profiles/$PROFILE.conf"
info "Profile loaded: $PROFILE"

# -------------------------------------------------------------------
# CLI Actions
# -------------------------------------------------------------------

handle_cli_actions

# -------------------------------------------------------------------
# Execution
# -------------------------------------------------------------------

run_modules
ok "All operations completed successfully"
